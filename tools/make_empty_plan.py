#!/usr/bin/env python3
"""Bundled fallback plan: the 56-day / 8-week challenge with the 5 empty meal slots per day (breakfast, lunch, dinner, snack, iced coffee), no foods and no carb types.
Day ids keep the established pattern (v2-w1-d1 ... v2-w8-d56) so hydration and other day-keyed data stay valid. Writes data/plan.json + data/plan-data.js (plan version 4).
The real plan (foods, quantities) lives in Supabase; the previous PDF plan is archived in data/archive/plan-v2.*"""
import json
WEEKDAYS = ['Saturday', 'Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday']
SLOTS = [('breakfast', 'Breakfast'), ('lunch', 'Lunch'), ('dinner', 'Dinner'), ('snack', 'Snack')]
plan = dict(version=4, source='Weight Loss Challenge - empty 56-day plan', weeks=[])
for w in range(1, 9):
    days = []
    for n in range((w - 1) * 7 + 1, w * 7 + 1):
        did = f'v2-w{w}-d{n}'
        meals = [dict(id=f'{did}-{k}', key=k, name=nm, items=[], pdfTotal=None) for k, nm in SLOTS]
        coffee = dict(id=f'{did}-coffee', key='coffee', name='Daily Iced Coffee', items=[], pdfTotal=None)
        days.append(dict(id=did, dayNumber=n, weekNumber=w, weekday=WEEKDAYS[(n - 1) % 7], meals=meals, coffee=coffee, pdfDailyTotal=None))
    plan['weeks'].append(dict(id=f'v2-w{w}', number=w, days=days))
json.dump(plan, open('data/plan.json', 'w'), indent=1)
open('data/plan-data.js', 'w').write('/* generated by tools/make_empty_plan.py (8-week empty plan) - do not edit by hand */\nwindow.NUTRITION_PLAN = ' + json.dumps(plan, separators=(',', ':')) + ';\n')
print('weeks', len(plan['weeks']), 'days', sum(len(w['days']) for w in plan['weeks']), 'meal slots', sum(len(d['meals']) + 1 for w in plan['weeks'] for d in w['days']))
