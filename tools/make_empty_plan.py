#!/usr/bin/env python3
"""Nutrition reset: write the 28-day plan with the same structure (day ids, weekdays, carb types, meal slots) but NO foods and no PDF reference values.
Source: data/archive/plan-v2.json (the imported PDF plan, kept as the recoverable backup).  Writes data/plan.json + data/plan-data.js (plan version 3)."""
import json
src = json.load(open('data/archive/plan-v2.json'))
SLOTS = [('breakfast', 'Breakfast'), ('lunch', 'Lunch'), ('dinner', 'Dinner'), ('snack', 'Snack')]
plan = dict(version=3, source='nutrition reset - empty 28-day plan', carbTargets=src['carbTargets'], weeks=[])
for w in src['weeks']:
    days = []
    for d in w['days']:
        meals = [dict(id=f"{d['id']}-{k}", key=k, name=n, items=[], pdfTotal=None) for k, n in SLOTS]
        coffee = dict(id=f"{d['id']}-coffee", key='coffee', name='Daily Iced Coffee', items=[], pdfTotal=None)
        days.append(dict(id=d['id'], dayNumber=d['dayNumber'], weekNumber=d['weekNumber'], weekday=d['weekday'], carbType=d['carbType'], meals=meals, coffee=coffee, pdfDailyTotal=None))
    plan['weeks'].append(dict(id=w['id'], number=w['number'], days=days))
json.dump(plan, open('data/plan.json', 'w'), indent=1)
open('data/plan-data.js', 'w').write('/* generated by tools/make_empty_plan.py (nutrition reset: empty 28-day plan) - do not edit by hand */\nwindow.NUTRITION_PLAN = ' + json.dumps(plan, separators=(',', ':')) + ';\n')
n = sum(len(m['items']) for w in plan['weeks'] for d in w['days'] for m in d['meals'] + [d['coffee']])
print('days', sum(len(w['days']) for w in plan['weeks']), 'meal slots', sum(len(d['meals']) + 1 for w in plan['weeks'] for d in w['days']), 'items', n)
